/*
  Email template review pack (npm run review:emails). Renders every email Reeldeal sends with
  sample values and screenshots each one at desktop (680px) and phone (375px) width.
    - Supabase Auth emails: supabase/templates/*.html (Go template fields replaced with samples)
    - App emails sent through Resend: src/server/email/templates.ts (invitation, reminder)
  Output: docs/review/email/ (HTML and PNG) plus docs/review/email/README.md. Sends nothing.
*/
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { chromium } from "playwright";
import { invitationEmail } from "../src/server/email/templates";

const OUT = "docs/review/email";
const SITE = "https://app.example.com";
const sample = { Email: "aroha@lakesidelodge.example", NewEmail: "aroha.ngata@lakesidelodge.example", SiteURL: SITE, TokenHash: "pkce_sample_token_hash_0123456789abcdef" };
const fill = (html: string) => html.replace(/\{\{\s*\.(\w+)\s*\}\}/g, (_, k: string) => (sample as Record<string, string>)[k] ?? `[${k}]`);

const invite = { to: "rangi@lakesidelodge.example", workspace: "Lakeside Lodge", inviter: "Aroha Ngata", role: "editor" as const, acceptUrl: `${SITE}/invite#rdl_inv_${"S".repeat(43)}`, expiresAt: "2026-11-25T08:00:00Z", siteUrl: SITE };
const emails: { id: string; name: string; subject: string; sender: string; html: string; expiry: string }[] = [
  { id: "confirmation", name: "Confirm signup", subject: "Confirm your Reeldeal email", sender: "Supabase Auth (Resend SMTP)", html: fill(readFileSync("supabase/templates/confirmation.html", "utf8")), expiry: "1 hour (Email OTP expiration 3600 s)" },
  { id: "recovery", name: "Reset password", subject: "Reset your Reeldeal password", sender: "Supabase Auth (Resend SMTP)", html: fill(readFileSync("supabase/templates/recovery.html", "utf8")), expiry: "1 hour" },
  { id: "email-change", name: "Change email address", subject: "Confirm your new Reeldeal email", sender: "Supabase Auth (Resend SMTP), to both addresses", html: fill(readFileSync("supabase/templates/email_change.html", "utf8")), expiry: "1 hour" },
  { id: "invitation", name: "Workspace invitation", subject: invitationEmail(invite).subject, sender: "The app (Resend API)", html: invitationEmail(invite).html, expiry: "7 days, exact date and time in the email" },
  { id: "invitation-reminder", name: "Invitation reminder (\"Resend\" on a pending invitation: a new link)", subject: invitationEmail({ ...invite, reminder: true }).subject, sender: "The app (Resend API)", html: invitationEmail({ ...invite, reminder: true }).html, expiry: "7 days from the new link" },
];

async function main() {
  mkdirSync(OUT, { recursive: true });
  const browser = await chromium.launch();
  for (const e of emails) {
    writeFileSync(join(OUT, `${e.id}.html`), e.html);
    for (const [label, width] of [["desktop", 680], ["phone", 375]] as const) {
      const page = await browser.newPage({ viewport: { width, height: 900 }, deviceScaleFactor: 1 });
      await page.setContent(e.html, { waitUntil: "load" });
      await page.screenshot({ path: join(OUT, `${e.id}-${label}.png`), fullPage: true });
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
      if (overflow) throw new Error(`${e.id} scrolls sideways at ${width}px`);
      await page.close();
    }
  }
  await browser.close();
  const rows = emails.map((e) => `| [${e.name}](${e.id}.html) | ${e.subject.replace(/\|/g, "\\|")} | ${e.sender} | ${e.expiry} | ![desktop](${e.id}-desktop.png) | ![phone](${e.id}-phone.png) |`).join("\n");
  writeFileSync(
    join(OUT, "README.md"),
    `# Email template review pack

Generated by \`npm run review:emails\` (sample data, nothing sent). Every email is plain inline-styled
HTML tables (Gmail, Outlook and Apple Mail safe), 520px wide at most, one column on phones (checked:
no sideways scrolling at 375px). Each has a text version (Resend) or Supabase's automatic one.

| Email | Subject | Sent by | Link expiry | Desktop (680px) | Phone (375px) |
|---|---|---|---|---|---|
${rows}

## Review checklist

- [ ] Wording and tone (Reeldeal voice: plain, warm, short)
- [ ] \`[COMPANY LEGAL NAME AND POSTAL ADDRESS]\` in every footer: owner copy still needed
- [ ] Sender: \`no-reply@mail.<domain>\` for account emails; invitations from \`EMAIL_FROM\` (e.g. \`Reeldeal <team@mail.<domain>>\`)
- [ ] Links: account emails use \`{{ .SiteURL }}/auth/callback?token_hash=…\` (any device); invitations put the token after \`#\`, so it never reaches a server log
- [ ] Expiry stated in each email matches the settings (Email OTP expiry 3600 s; invitations 7 days)
- [ ] Nothing sensitive in subjects or preheaders (no tokens; names only)

## Safety properties (tested: \`src/server/email/email.test.ts\`)

- Every value is HTML-escaped (a workspace called \`<script>\` renders as text).
- One send per invitation: \`Idempotency-Key: invitation:<id>\`, so a retried action can't email twice.
- Nothing about a message is logged: no address, link, body or API key; only the outcome.
- Without \`RESEND_API_KEY\` and \`EMAIL_FROM\` nothing is sent and the admin copies the link instead.
`,
  );
  console.log(`wrote ${emails.length} emails × 2 widths to ${OUT}`);
}
main().catch((e) => {
  console.error(e);
  process.exit(1);
});
